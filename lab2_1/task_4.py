set1 = set(map(int, input("Введите числа(целые) первого набора через пробел: ").split()))
set2 = set(map(int, input("Введите числа(целые) второго набора через пробел: ").split()))

# 1. Числа, которые есть в обоих наборах (пересечение множеств)
common = set1 & set2

# 2. Числа, которые уникальны для каждого набора
only_in_set1 = set1 - set2
only_in_set2 = set2 - set1

# 3. Числа из обоих наборов, исключая общие (симметрическая разность)
symmetric_diff = set1 ^ set2

# Выводим результаты
print("1. Общие числа:", common)
print("2. Только в первом наборе:", only_in_set1)
print("   Только во втором наборе:", only_in_set2)
print("3. Все числа без общих:", symmetric_diff)
