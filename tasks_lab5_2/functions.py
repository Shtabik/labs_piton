def count_words(sentence):
    """
    Задача 1. Подсчет слов в предложении.
    Разбивает строку по пробелам и возвращает количество слов.
    """
    if not sentence:
        return 0
    return len(sentence.split())


def find_unique(lst):
    """
    Задача 2. Поиск уникальных элементов.
    Возвращает список элементов, которые встречаются в исходном списке только один раз.
    """
    # Считаем количество вхождений каждого элемента
    counts = {}
    for item in lst:
        counts[item] = counts.get(item, 0) + 1

    # Возвращаем те, у которых счетчик равен 1.
    # Этот способ сохраняет исходный порядок элементов.
    return [item for item in lst if counts[item] == 1]


def is_palindrome(obj):
    """
    Задача 3. Палиндром.
    Проверяет, является ли слово или число палиндромом.
    Игнорирует регистр и пробелы.
    """
    # Преобразуем в строку, убираем пробелы и приводим к нижнему регистру
    s = str(obj).replace(" ", "").lower()
    return s == s[::-1]


def are_anagrams(str1, str2):
    """
    Задача 4. Анаграммы.
    Проверяет, состоят ли строки из одних и тех же букв.
    Игнорирует регистр и пробелы.
    """

    def clean_string(s):
        return s.replace(" ", "").lower()

    # Сортируем буквы в обеих строках и сравниваем
    return sorted(clean_string(str1)) == sorted(clean_string(str2))


def combine_dicts(dict1, dict2):
    """
    Задача 5. Слияние словарей.
    Возвращает новый словарь, объединяя два переданных.
    """
    # Создаем копию первого словаря, чтобы не менять исходный
    result = dict1.copy()
    # Добавляем данные из второго (если ключи совпадают, значения из dict2 перезапишут dict1)
    result.update(dict2)
    return result