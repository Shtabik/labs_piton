import numpy as np

# Матрица коэффициентов (A)
A = np.array([
    [-2,   -8.5, -3.4,  3.5],
    [0,    2.4,  0,    8.2],
    [2.5,  1.6,  2.1,  3],
    [0.3, -0.4, -4.8,  4.6]
])

# Вектор правых частей (B)
B = np.array([-1.88, -3.28, -0.5, -2.83])

# Решение системы X = A^(-1) * B
X = np.linalg.inv(A).dot(B)

# Округляем до одного знака после запятой
X_rounded = np.round(X, 1)

# Вывод результата
print("Решение системы (x1, x2, x3, x4):", X_rounded)
