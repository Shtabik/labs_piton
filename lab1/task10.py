a = int(input("Введите число a: "))
b = int(input("Введите число b (b не равное 0): "))

print("Сумма:", a + b, "- Это просто сложение чисел a и b.")
print("Разность:", a - b, "- Это разница между числами a и b.")
print("Произведение:", a * b, "- Это произведение чисел a и b.")
print("Частное:", a / b, "- Это результат деления числа a на число b.")
print("Остаток:", a % b, "- Это остаток от деления числа a на число b ")
print("Степень:", a ** b, "- Это число a, возведенное в степень b ")

